#!/usr/bin/env python3
"""Robot meshes split for Webots (Gazebo keeps the originals).

Webots casts shadows (stencil shadow volumes) only from meshes below 21'845 triangles and warns
above 100'000 vertices. The CAD chassis is 248k triangles and a steering pod 22.4k, so the robot
cast almost no shadow. Each mesh is split, at full detail, into OBJ objects of at most CHUNK
triangles (files <name>_0.obj, <name>_1.obj, ...) that build_webots.py puts in separate Shapes.
(Quadric decimation to 60k shredded the chassis' thin plates, so there is none.)

usage: python tools/webots_meshes.py      (writes wcr_description/meshes/webots/*.obj)
needs: pip install trimesh numpy
"""
import math
from pathlib import Path

import numpy as np
import trimesh

ROOT = Path(__file__).resolve().parents[1]
MESHES = ROOT / 'wcr_description' / 'meshes'
OUT = MESHES / 'webots'
CHUNK = 20000
CREASE = math.radians(35)     # edges sharper than this keep split normals
SPLIT = ['chassis_body.obj', 'active_wheel.obj']


def chunks(m):
    """Split faces into groups of <= CHUNK, keeping connected parts together where possible."""
    groups, cur = [], []
    for comp in sorted(trimesh.graph.connected_components(m.face_adjacency, nodes=np.arange(len(m.faces))),
                       key=lambda c: m.triangles_center[c].mean(0)[0]):
        for i in range(0, len(comp), CHUNK):
            part = list(comp[i:i + CHUNK])
            if len(cur) + len(part) > CHUNK:
                groups.append(cur)
                cur = []
            cur += part
    return groups + [cur] if cur else groups


def write_objs(m, stem):
    """One file per chunk: Webots ignores Mesh.name for OBJ objects (a Shape loads every object)."""
    for old in OUT.glob(f'{stem}*.obj'):
        old.unlink()
    groups = chunks(m)
    for k, faces in enumerate(groups):
        sub = trimesh.Trimesh(m.vertices, m.faces[faces], process=False)
        sub.remove_unreferenced_vertices()
        sub = trimesh.graph.smooth_shade(sub, angle=CREASE)
        out = [f'# generated by tools/webots_meshes.py from {stem}.obj', f'o {stem}_{k}']
        out += [f'v {a:.5f} {b:.5f} {c:.5f}' for a, b, c in sub.vertices]
        out += [f'vn {a:.4f} {b:.4f} {c:.4f}' for a, b, c in sub.vertex_normals]
        out += [f'f {a}//{a} {b}//{b} {c}//{c}' for a, b, c in sub.faces + 1]
        (OUT / f'{stem}_{k}.obj').write_text('\n'.join(out) + '\n')
    return len(groups)


def main():
    OUT.mkdir(exist_ok=True)
    for name in SPLIT:
        m = trimesh.load(MESHES / name, process=True)      # merge the split-normal vertices
        n = write_objs(m, Path(name).stem)
        print(f'{name}: {len(m.faces)} triangles in {n} object(s)')


if __name__ == '__main__':
    main()
